export function applyCharacterProfileDepth(
  character: BibleCharacter,
): BibleCharacter {
  const depth = CHARACTER_PROFILE_DEPTH[character.slug];
  if (!depth) return character;
  const verses = depth.verses ?? character.verses;
  const verse = depth.verses?.[0] ?? character.verse ?? verses?.[0];
  return {
    ...character,
    ...depth,
    keywords: [...new Set([...(character.keywords ?? []), ...(depth.keywords ?? [])])],
    lessons: depth.lessons ?? character.lessons,
    verses,
    verse,
  };
}
